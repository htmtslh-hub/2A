import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { writeFileSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
process.env.PLAYWRIGHT_BROWSERS_PATH = resolve('_design/.browsers');
const { chromium } = await import('../../../../../../_design/.tooling/node_modules/playwright/index.mjs');
const product = resolve('web/product/giao-dien-web/leaflit');
const source = resolve(product,'source');
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width:375,height:812 } });
const page = await context.newPage();
await page.goto(pathToFileURL(resolve(source,'index.html')).href);
await page.keyboard.press('Tab');
const focus = await page.evaluate(() => ({text:document.activeElement.textContent,outline:getComputedStyle(document.activeElement).outlineWidth}));
await page.locator('.menu-toggle').click();
await page.setViewportSize({width:1440,height:900});
await page.setViewportSize({width:375,height:812});
const resizeClosed = await page.locator('.menu-toggle').getAttribute('aria-expanded') === 'false';
await page.setViewportSize({width:1440,height:900});
await page.evaluate(() => document.body.style.zoom='2');
await page.waitForTimeout(450);
const zoom200 = await page.evaluate(() => ({width:document.documentElement.clientWidth,scrollWidth:document.documentElement.scrollWidth,overflow:[...document.querySelectorAll('body *')].filter(e=>e.getBoundingClientRect().right>document.documentElement.clientWidth).map(e=>({tag:e.tagName,class:String(e.className),right:e.getBoundingClientRect().right}))}));
const luminance = hex => {
  const c=hex.match(/\w\w/g).map(v=>parseInt(v,16)/255).map(v=>v<=.04045?v/12.92:((v+.055)/1.055)**2.4);
  return c[0]*.2126+c[1]*.7152+c[2]*.0722;
};
const ratio=(a,b)=>{const x=luminance(a),y=luminance(b);return +( (Math.max(x,y)+.05)/(Math.min(x,y)+.05) ).toFixed(2);};
const contrast = [['292b28','f8f7f4'],['646761','f8f7f4'],['646761','eeede8'],['ffffff','896443'],['ffffff','755353'],['ffffff','173741'],['ffffff','3e5e70'],['ffffff','172c31'],['ffffff','48565c'],['775411','f8f7f4']].map(([fg,bg])=>({fg,bg,ratio:ratio(fg,bg)}));
const files=readdirSync(source,{recursive:true}).filter(f=>statSync(resolve(source,f)).isFile()).map(f=>f.replaceAll('\\','/')).sort();
const manifest=files.map(f=>({file:f,sha256:createHash('sha256').update(readFileSync(resolve(source,f))).digest('hex')}));
writeFileSync(resolve(product,'reviews/1.0.0/supplemental.json'),JSON.stringify({focus,resizeClosed,zoom200,contrast,manifest},null,2));
console.log(JSON.stringify({focus,resizeClosed,zoom200,contrast}));
await browser.close();
