import { resolve } from 'node:path';
process.env.PLAYWRIGHT_BROWSERS_PATH = resolve('_design/.browsers');
const { chromium } = await import('../../../../../../_design/.tooling/node_modules/playwright/index.mjs');
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, recordVideo: { dir: resolve('web/product/giao-dien-web/velora/reviews/1.1.0/video'), size: { width: 1280, height: 900 } } });
const page = await context.newPage();
await page.goto('http://127.0.0.1:4339');
await page.waitForTimeout(900);
await page.locator('[data-next]').click(); await page.waitForTimeout(1100);
await page.locator('[data-next]').click(); await page.waitForTimeout(1100);
await page.locator('[data-next]').click(); await page.waitForTimeout(1100);
await page.locator('[data-prev]').click(); await page.waitForTimeout(1100);
await page.locator('[data-open]').click(); await page.waitForTimeout(1100);
await page.locator('[data-info="specs"]').click(); await page.waitForTimeout(700);
await page.locator('[data-category="frame"]').click();
await page.locator('#frame-panel label').filter({ has: page.locator('input[value="graphite"]') }).click(); await page.waitForTimeout(700);
await page.locator('[data-category="wheels"]').click();
await page.locator('#wheels-panel label').filter({ has: page.locator('input[value="disc"]') }).click(); await page.waitForTimeout(1000);
await page.locator('[data-back]').click(); await page.waitForTimeout(1100);
const video = page.video();
await context.close();
await video.saveAs(resolve('web/product/giao-dien-web/velora/reviews/1.1.0/demo.webm'));
await browser.close();
